import { sql } from "drizzle-orm";
import { check, date, index, integer, pgTable, text, timestamp, uuid } from "drizzle-orm/pg-core";
import { domesticOrders } from "./domestic-orders";
import { users } from "./users";

/**
 * ============================================================================
 * 내자 정리 — 한 줄에 달리는 납기 요청일들
 * ============================================================================
 * 원래 납기요청일은 domestic_orders 의 칸 하나(requested_due_date)였다. 한 줄에
 * 날짜가 하나뿐이라는 뜻인데, 실제 발주는 그렇지 않다 — **분할 납품**이 있다.
 * 같은 발주 건을 나눠 납품하면 1차분·2차분에 각각 날짜가 붙고, 칸이 하나면
 * 사람은 그 둘을 "2026-01-20, 2026-02-15" 처럼 한 칸에 몰아 적거나(그러면
 * date 컬럼이 아니라 글자가 된다) 아예 못 적고 다시 Excel 로 돌아간다.
 * 그래서 날짜를 **딸린 표**로 뺀다.
 *
 * ── ON DELETE CASCADE 인 이유 ───────────────────────────────────────────
 * 이 날짜는 **그 발주 줄에 딸린 값**이다. 발주 줄이 없으면 "무엇의 납기인가"를
 * 말할 수 없어서, 부모 없이 남은 날짜는 그 자체로 뜻이 없다.
 *
 * 이 저장소가 다른 곳에서 SET NULL / RESTRICT 를 쓰는 것은 그 기록들이
 * **부모보다 오래 살아야 하기 때문**이다 — attachments 의 증빙 사진과
 * domestic_orders 의 세금계산서·입금 사실이 그렇다(각 파일의 '영구 삭제돼도'
 * 항목). 회계 기록은 그 거래의 원인이 지워진 뒤에도 남아야 한다. 납기
 * 요청일에는 그런 성질이 없다: 발주 줄이 사라지면 함께 사라지는 것이 맞고,
 * 남겨 두면 어느 발주의 날짜인지 영영 알 수 없는 고아 행만 쌓인다.
 *
 * 참고로 domestic_orders 의 삭제는 소프트 삭제(is_deleted)라서 화면에서 지운
 * 줄은 이 표를 건드리지 않는다. CASCADE 가 실제로 도는 것은 그 행을 정말로
 * 지울 때뿐이다.
 *
 * ── 소프트 삭제 4칼럼도 version 도 두지 않는다 ─────────────────────────────
 * 이 표에는 **직접 고치는 경로가 없다.** 저장은 언제나 부모 줄을 통째로
 * 저장하는 한 번의 트랜잭션이고, 그 안에서 이 줄들은 통째로 지워지고 다시
 * 들어간다(mutations/domestic-orders.ts). 동시 수정을 막는 일은 부모의
 * version 이 이미 하고 있으므로 여기에 또 두면 두 벌이 어긋난다.
 *
 * ── display_order 는 사람이 정한 차례다 ────────────────────────────────
 * 1차분·2차분처럼 순서가 곧 뜻인 값이라, 날짜순으로 다시 정렬하지 않는다 —
 * 폼에 늘어놓은 차례가 그대로 번호가 되고(저장할 때 1부터 매긴다), 화면은 그
 * 차례대로 읽는다. domestic_orders.display_order 와 같은 이유로 NULL 을
 * 허용한다(옮겨 온 값에 차례가 없을 수 있다).
 *
 * ── 🔴 납품일·납품자도 **이 행에 달린다** (2026-11-08) ────────────────────
 * 사용자 요구 원문: 「납기 요청일을 여러줄로 두면, 납품일, 납품자도 그 수에 맞게
 * 설정할 수 있도록」. 그래서 날짜 행 하나가 **「언제까지 달라고 했고, 언제 누가
 * 보냈는가」 한 쌍**이 된다 — 1번 줄의 납기요청일과 1번 줄의 납품일이 같은 행에
 * 있으므로 둘을 잇는 규칙을 코드 어디에도 적을 필요가 없다(사용자 결정 1:
 * 「납기요청일 1번 줄 ↔ 납품일 1번 줄 — 행이 묶인다」).
 *
 * 🔴 **부모 표의 `delivered_date` · `delivered_by` 는 지우지 않았다**(사용자 결정
 * 11). 그 칸은 PO 시스템(dss-po)이 같은 DB 에서 쓰고 있어서, 지우면 그쪽 저장이
 * 깨진다. 대신 **A/S 는 그 칸을 더 이상 그리지 않는다** — 화면에 보이는 납품일은
 * 전부 이 표에서 나온다(queries/domestic-orders.ts 의 deliveredDateLines).
 * `requested_due_date` 가 걸은 길과 같은 모양이고, 같은 까닭으로 한쪽만 남긴다:
 * 같은 뜻이 두 자리에 살아 **화면에 동시에 보이면** 어느 쪽이 맞는지 답할 수 없다.
 *
 * ── 🔴 `due_date` 가 NOT NULL 인 것이 이 설계의 울타리다 ──────────────────
 * 「납기요청일 없이 납품일만 있는 행」은 **들어올 자리가 없다.** 바꾸지 않았다:
 *  · 이 표의 뜻이 "발주서에 적힌 납기일"이고, 그 날짜가 없는 행은 위 머리말대로
 *    **빈 줄이지 자료가 아니다.** 날짜를 NULL 로 열면 이 표는 「납기일 표」와
 *    「납품 기록 표」 둘을 겸하게 되고, 조회·정렬(display_order → due_date)이
 *    말이 안 되는 행을 다루기 시작한다.
 *  · 운영 실측(2026-11-07)에서 「납품일이 적혔는데 납기요청일 행이 없는 줄」이
 *    **0줄**이었다 — 지금 급한 문제가 아니다.
 * 🔵 그 대신 **납품일을 적으려면 납기요청일이 먼저 있어야 한다.** 화면이 그 말을
 * 한다(DomesticOrderDeliveriesCell — 행이 없으면 편집칸 대신 그 안내가 선다).
 *
 * ── 🔴 CASCADE 는 그대로다 — 납품 기록에도 「부모보다 오래 살 성질」이 없다 ──
 * 회계 기록(세금계산서·입금)이 SET NULL 인 것은 **그 거래의 원인이 지워져도 남아야
 * 하기 때문**인데, 납품 기록은 그 거래 줄 자체에 붙은 사실이라 줄이 사라지면
 * 「무엇을 납품했는가」를 말할 수 없다. 옛 자리(`domestic_orders.delivered_date`)도
 * 그 줄의 칼럼이었으므로 **수명이 한 글자도 달라지지 않는다** — 자리를 옮기면서
 * 수명까지 바꾸면 무엇 때문에 달라졌는지 나중에 가릴 수 없다.
 * 🔵 화면에서 지우는 일은 소프트 삭제라 이 표를 건드리지 않는다(위 머리말).
 *
 * ── 🔴 **회차마다 [완료 처리]가 있다** (2026-11-08) ─────────────────────
 * 사용자 결정 7·8: 「납품일이 여러개라면 **각각에 [완료처리]버튼**을 만들어줘」·
 * 「**마지막 분할분이 찍히면 자동으로**」 내자 줄이 완료된다. 그래서 행 하나가
 * 「언제까지 달라고 했고 · 언제 누가 보냈고 · **그 회차를 끝냈는가**」 한 벌이 된다.
 *
 * 🔴 **이 두 칸은 `replaceDueDates` 가 **다시 적어 주는** 값이다.** 이 표의 저장은
 * 여전히 「통째로 지우고 받은 목록으로 다시 넣기」인데(파일 머리말), 완료 표시는
 * **폼이 보내는 값이 아니다** — 보내게 두면 줄 수정 폼의 payload 하나로 승인 없이
 * 완료를 찍을 수 있다. 그래서 저장 통로가 지우기 **전에** 읽어 두었다가 같은 차례
 * (`display_order`)의 새 행에 **서버가 직접** 되얹는다
 * (mutations/domestic-orders.ts 의 replaceDueDates — 「완료 표시를 되얹는다」).
 * 🔵 차례가 줄어드는 저장은 울타리가 막는다(domain/domestic-order-due-date-rows.ts
 * 의 결정 13 짝 — 「완료 처리된 회차가 있으면 줄을 지울 수 없다」). 그래서 되얹기가
 * 엉뚱한 회차로 밀릴 자리가 없다.
 *
 * ── PII ────────────────────────────────────────────────────────────────
 * note 는 사람이 자유롭게 적는 칸이라("1차분", "김유진 과장 확인분") 담당자
 * 이름이 섞일 수 있다. 🔴 **`delivered_by` 는 그보다 확실하다 — 사람 이름 칸이다**
 * (users FK 가 아니라 시트 그대로의 글자다. 부모 표의 같은 이름 칸과 같은 규칙).
 * 부모 표의 메모 칸들과 같은 규칙이다 — 로그나 오류 보고로 그대로 내보내지 않는다.
 * ============================================================================
 */
export const domesticOrderDueDates = pgTable(
  "domestic_order_due_dates",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // 딸린 값이라 CASCADE 다 — 파일 헤더의 'ON DELETE CASCADE 인 이유' 참조.
    domesticOrderId: uuid("domestic_order_id")
      .notNull()
      .references(() => domesticOrders.id, { onDelete: "cascade" }),
    // 발주서에 적힌 납기 요청일. 날짜 없는 줄은 이 표에 아예 들어오지 않으므로
    // NOT NULL 이다 — "날짜 없는 납기일"은 빈 줄이지 자료가 아니다.
    dueDate: date("due_date").notNull(),
    /** "1차분" 같은 짧은 메모. 여러 날짜를 구분하는 유일한 단서다. */
    note: text("note"),
    /**
     * 🔴 이 회차를 **실제로 보낸 날**(2026-11-08). NULL 이면 아직 안 보냈다.
     *
     * 위 due_date 와 **뜻이 다른 날짜다** — 저쪽은 「언제까지 달라고 했는가」이고
     * 이쪽은 「언제 보냈는가」다. 한 행에 나란히 두는 것은 그 둘이 **같은 회차의
     * 약속과 결과**이기 때문이고, 그래서 1차분의 납품일을 2차분 줄에서 찾는 일이
     * 생기지 않는다.
     *
     * 🔴 **수리 건이 붙은 줄에서는 그 건의 `actual_shipment_date` 와 같은 날짜로
     * 맞춰진다**(양방향 — domain/delivered-date-link.ts). 출하 완료 전이가 이 칸에
     * 날짜를 찍고, 사람이 어느 쪽을 고쳐도 상대가 따라온다. 맞출 수 없는 모양
     * (행이 여럿·아직 출하 전·인수일보다 이른 날)에서는 **조용히 넘기지 않고
     * 사람에게 말한다.**
     */
    deliveredDate: date("delivered_date"),
    /**
     * 그 회차를 보낸 사람. 🔴 **users FK 가 아니라 시트 그대로의 글자다**(부모 표의
     * 같은 이름 칸과 같다 — 거기 적히는 것은 우리 계정이 아닐 수도 있다).
     *
     * 🔴 PII — 파일 머리말의 PII 항목. 로그·오류 문구에 그대로 싣지 않는다.
     *
     * 🔵 **자동으로 찍히지 않는다.** 출하 완료 전이는 날짜만 찍는다 — 「누가
     * 보냈는가」는 전이를 누른 사람과 다를 수 있어서, 지어내면 그 줄의 유일한
     * 단서가 거짓이 된다. 적는 자리는 사람이 여는 편집칸뿐이다.
     */
    deliveredBy: text("delivered_by"),
    /**
     * 🔴 **이 회차를 [완료 처리]한 시각**(2026-11-08). NULL 이면 아직 안 끝났다.
     *
     * 부모 줄의 `domestic_orders.completed_at` 과 **뜻이 같고 단위만 다르다** — 저쪽은
     * 「이 발주 줄을 끝냈다」, 이쪽은 「이 회차를 끝냈다」. 둘은 한 방향으로 묶인다:
     * **모든 회차가 끝나면 부모 줄이 자동으로 완료된다**(사용자 결정 8).
     *
     * 🔴 **이 칸이 차려면 그 회차의 [기타건 최종 출하 승인]이 유효해야 한다**(사용자
     * 결정 13). 판정도 울타리도 저장 통로가 트랜잭션 안에서 쥔다
     * (mutations/domestic-orders.ts) — 이 표에는 그것을 표현할 자리가 없다(승인 행은
     * `repair_case_approvals` 에 있고, 그 행이 이 행을 가리키는 방식은 **id 가 아니라
     * 회차 번호**다. 까닭은 그 표의 `due_date_row_order` 주석에 있다).
     */
    completedAt: timestamp("completed_at", { withTimezone: true }),
    /**
     * 그 회차를 완료 처리한 사람. 🔴 **부모 줄의 `completed_by` 와 같은 모양**이다 —
     * users FK · ON DELETE RESTRICT(기록이 조용히 뭉개지지 않게).
     *
     * 🔵 `delivered_by`(시트 그대로의 글자)와 **다른 종류의 칸**이다. 저쪽은 「고객에게
     * 보낸 사람」이라 우리 계정이 아닐 수 있고, 이쪽은 「이 시스템에서 단추를 누른
     * 사람」이라 언제나 계정이다.
     */
    completedBy: uuid("completed_by").references(() => users.id, { onDelete: "restrict" }),
    /** 사람이 정한 차례. 파일 헤더의 'display_order 는 사람이 정한 차례다'. */
    displayOrder: integer("display_order"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // 목록 조회가 보이는 줄들의 날짜를 한 번에 걷어 오는 길이다(N+1 을 만들지
    // 않으려고 domestic_order_id IN (...) 로 한 번에 읽는다). 부분 인덱스가
    // 아닌 것은 이 표에 is_deleted 가 없기 때문이다.
    index("domestic_order_due_dates_order_id_idx").on(table.domesticOrderId),
    // 🔴 완료 두 칸은 **언제나 함께 움직인다** — 부모 표의 completed_at/completed_by 가
    // 지키는 규칙 그대로다(mutations/domestic-orders.ts 의 '두 칸은 언제나 함께').
    // 한쪽만 남으면 「완료 시각은 없는데 완료한 사람은 있는」 행이 생기고, 그때 그
    // 회차가 완료인지 아닌지 답할 방법이 없다 — 판정은 completed_at 하나로만 한다.
    check(
      "domestic_order_due_dates_completed_columns_together",
      sql`(completed_at IS NULL AND completed_by IS NULL) OR (completed_at IS NOT NULL AND completed_by IS NOT NULL)`
    ),
  ]
);
