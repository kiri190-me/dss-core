import { sql } from "drizzle-orm";
import { check, index, pgTable, text, timestamp, uuid } from "drizzle-orm/pg-core";
import { users } from "./users";

/**
 * ============================================================================
 * 통합 승인함에서 맡긴 결재권 위임 — **포털이 써 주는 자리**
 * ============================================================================
 * 사내 결재권 위임을 포털(dss-auth) 한 곳에 모으기로 한 결정(2026-11-13, 설계
 * B-1)의 **저장 쪽**이다. 2026-11-16 저녁에 방식이 뒤집혔다(설계 B-12):
 *
 *   · 그 전(B-3): 결재할 때마다 **각 시스템이 포털에 물었다**(pull). 결재 길목에
 *     망 호출이 있었고, 포털이 느리면 그만큼 [승인] 단추가 붙들렸다.
 *   · 지금(B-12): **포털이 지정·철회할 때 각 시스템에 전파하고**(push), 각 시스템은
 *     **제 표만 읽는다.** 이 표가 A/S 쪽의 그 「제 표」다.
 *
 * 🔴 **그래서 이 표의 줄은 A/S 가 만들지 않는다.** 들어오는 길은
 * `POST /api/integration/delegations` 하나뿐이고, 그 통로는 포털이 서명한 서비스
 * 토큰으로만 열린다. 화면에도, 서버 액션에도 이 표에 쓰는 자리가 없다.
 *
 * ── 🔴 `id` 의 주인이 포털이다 ──────────────────────────────────────────
 * `defaultRandom()` 이 **없다.** 번호는 포털이 정해 보내고 여기서는 받아 적는다
 * (설계 B-12 의 5번). 양쪽이 같은 줄을 같은 번호로 가리켜야 **철회가 맞고**(철회는
 * `id` 하나로 온다) 나중에 어긋남 점검(B-14)이 두 표를 맞댈 수 있다. 여기서 번호를
 * 새로 만들면 그 두 가지가 **오류 없이** 안 된다 — 철회가 아무 줄도 못 찾고, 점검은
 * 같은 위임을 서로 다른 줄로 읽는다.
 *
 * ── 🔴 이 표의 줄은 **A/S 에서 되돌릴 수 없다** ─────────────────────────
 * 되돌리기는 **통합 승인함에서만** 한다(설계 B-12 의 3번). 여기서 `revoked_at` 을
 * 적어도 포털은 모르므로, 승인함에는 살아 있는 위임이 그대로 보이고 다음 전파 한
 * 번이면 되살아난다 — **사람은 거뒀다고 믿는데 안 거둬진** 상태가 된다. 그래서
 * 이 칸은 **포털이 보낸 `revoke` 를 받아 적는 자리**일 뿐이다.
 * 🔵 A/S 화면의 [되돌리기] 단추가 붙는 곳은 아래 `approval_route_delegations` 다.
 *
 * ── 🔴 `approval_route_delegations` 와 **다른 표**이고 둘 다 살아 있다 ───
 * 설계 B-4 가 「포털 위임과 각 시스템 위임을 둘 다 살려 둔다」로 못 박았다. 판정은
 * **합집합**이다 — 어느 쪽에 맡겨 두었든 대신 누를 수 있다. 칸 모양이 닮았다고
 * 한쪽을 다른 쪽으로 옮기지 마라. 둘은 **만드는 사람도 되돌리는 자리도 다르다**:
 *
 *   | | `approval_route_delegations` | `portal_approval_delegations`(이 표) |
 *   |---|---|---|
 *   | 누가 만드나 | A/S 화면에서 사람이 | **포털이 전파해서** |
 *   | `id` 주인 | A/S(`defaultRandom`) | **포털** |
 *   | 되돌리는 자리 | A/S 화면 | **통합 승인함에서만** |
 *   | 누가 세웠나 | `created_by_user_id` 에 남는다 | 🔴 **칸이 없다** — 포털이 안다 |
 *
 * 🔴 **`created_by_user_id` 와 `revoked_by_user_id` 를 두지 않은 것은 의도다.**
 * 누가 지정하고 누가 거뒀는지는 **포털 쪽 줄과 포털 감사 로그**가 쥐고 있고, 그 사람은
 * A/S 계정이 아예 없을 수도 있다(승인함은 일곱 사이트의 사람을 전부 본다). 빈 칸을
 * 만들어 두면 「비어 있다」가 「본인이 했다」로 읽히는 날이 온다.
 *
 * ── 🔴 열쇠는 A/S `users.id` 다. 포털 번호가 아니다 ─────────────────────
 * 포털은 제 `users.id`(= ID 토큰의 `sub`)로 보내고, **받는 통로가 A/S 열쇠로 바꿔**
 * 넣는다(설계 B-12 의 4번 — `users.sso_subject` 로 찾는다). 그래서 진짜 외래키를 걸 수
 * 있고, 결재 판정이 하는 비교(`users.id`)와 같은 값이 된다.
 * 🔴 **둘 중 하나라도 A/S 계정으로 안 바뀌면 줄을 만들지 않는다 — 그리고 그것은
 * 오류가 아니다**(통로가 `not_applicable` 로 답한다). A/S 계정이 없는 사람은 여기서
 * 결재할 일이 없으니 위임도 뜻이 없는데, 그것을 실패로 돌려주면 포털이 **지정 자체를
 * 거절한다**(B-13) — 「A/S 계정이 없는 사람에게는 위임을 아예 못 맡기는」 일이 된다.
 *
 * ── `scope` 칸을 두지 않는다 ────────────────────────────────────────────
 * 설계 B-8: 위임은 **그 시스템의 결재 전부**에 적용된다. 「A/S 의 견적서만 맡긴다」
 * 같은 한정이 필요해지면 그때 칸을 더한다 — 지금 두면 결재 갈래 이름을 포털과
 * 맞춰야 하는데 그 이름의 주인이 하나가 아니다(설계 D-4).
 *
 * ── 겹치는 기간을 DB 로 막지 않는다 ─────────────────────────────────────
 * `approval_route_delegations` 와 같은 판단이다 — 두 사람이 동시에 자리를 비울 수
 * 있고, 한 사람에게 기간을 나눠 두 번 맡길 수도 있다. 중복은 판정 함수가 거른다.
 * 🔴 게다가 여기서는 **겹침을 거절하면 전파가 실패한다** — 포털이 이미 받아 둔 지정이
 * 이쪽에서만 거절되면 B-13 에 걸려 지정 자체가 거절된다.
 * ============================================================================
 */
export const portalApprovalDelegations = pgTable(
  "portal_approval_delegations",
  {
    /**
     * 🔴 **포털이 정한 번호를 그대로 받는다.** `defaultRandom()` 이 없는 까닭은
     * 머리말에 있다 — 철회도 어긋남 점검도 이 번호가 양쪽에서 같아야 돈다.
     *
     * 🔵 같은 번호로 두 번 와도 **한 줄**이다. 그 멱등을 지키는 것이 이
     * 기본키이고(두 번째는 `ON CONFLICT (id) DO UPDATE` 로 덮어쓴다), 포털이
     * 마음 놓고 재시도할 수 있는 근거가 그것이다.
     */
    id: uuid("id").primaryKey(),
    /**
     * 결재권을 맡긴 사람 — **A/S `users.id`**. 포털 번호를 통로가 바꿔 넣는다.
     *
     * RESTRICT 는 이 저장소의 사람 참조 관례이고, 바로 옆
     * `approval_route_delegations` 의 네 참조와 **같은 값**이다. 사용자는
     * 소프트삭제만 하므로 행이 사라질 일이 없고, 실수로라도 하드 삭제가 시도되면
     * 여기서 막힌다.
     */
    delegatorUserId: uuid("delegator_user_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    /** 대신 눌러 줄 사람 — **A/S `users.id`**. 같은 까닭으로 RESTRICT. */
    delegateUserId: uuid("delegate_user_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    startsAt: timestamp("starts_at", { withTimezone: true }).notNull(),
    /**
     * 🔴 **이 순간은 포함하지 않는다**(반열린 구간 `[starts_at, ends_at)`) —
     * `approval_route_delegations` 와 **같은 규칙**이다. 판정 함수 하나가 두 표의
     * 줄을 함께 보므로(합집합, 설계 B-4) 규칙이 갈리면 같은 날짜가 표마다 다르게
     * 산다. 포털도 같은 뜻으로 보낸다.
     */
    endsAt: timestamp("ends_at", { withTimezone: true }).notNull(),
    /**
     * 사유. 포털에서 안 적었으면 **빈 글자**가 온다 — 널을 받지 않는 것은 옆 표와
     * 같은 판단이다(읽는 쪽마다 `?? ""` 를 적게 만들지 않는다).
     */
    reason: text("reason").notNull().default(""),
    /**
     * 되돌린 시각. 아직 살아 있으면 `NULL`.
     *
     * 🔴 **이 칸을 A/S 가 스스로 적는 자리는 없다** — 포털이 보낸 `revoke` 를 받아
     * 적을 뿐이다(머리말). 🔵 옆 표와 달리 `revoked_by_user_id` 짝이 없다: 거둔
     * 사람은 포털이 알고, 그 사람은 A/S 계정이 아닐 수도 있다.
     */
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
    /**
     * 🔴 **언제 받았나.** 만든 때도 고친 때도 아니라 **마지막으로 전파를 받아 적은
     * 때**다(`upsert` 든 `revoke` 든 이 값이 새로 찍힌다).
     *
     * 쓰임새가 하나다 — 어긋남 점검(설계 B-14). 포털에는 있는데 여기 없는 줄,
     * 여기만 남은 줄, 내용이 다른 줄을 맞대어 볼 때 **어느 쪽이 더 나중 것인지**를
     * 가를 값이 없으면 점검이 「다르다」까지만 말하고 멈춘다.
     * 🔵 `created_at` 을 따로 두지 않은 까닭: 이 표의 줄은 A/S 가 만든 것이 아니라
     * **받아 적은 사본**이고, 「처음 만들어진 때」는 포털 줄이 쥐고 있다.
     */
    syncedAt: timestamp("synced_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // 「내가 지금 누구를 대신하나」 — 결재 판정·목록·종이 이 모양으로 묻는다.
    // 대리인으로 좁히고(`delegate_user_id`), 되돌리지 않은 줄만 남기고(`revoked_at
    // IS NULL`), 아직 안 끝난 것만 본다(`ends_at > now()`). 칸 순서가 그 순서다.
    // 🔵 옆 `approval_route_delegations` 의 같은 색인과 **글자 그대로 같은 모양**이다
    // — 판정이 두 표를 함께 읽으므로 한쪽만 색인이 다르면 그쪽만 느려진다.
    index("portal_approval_delegations_delegate_active_idx").on(
      table.delegateUserId,
      table.revokedAt,
      table.endsAt
    ),
    // 끝이 시작보다 뒤여야 한다. 같아도 안 된다 — 끝을 포함하지 않으므로
    // `ends_at = starts_at` 인 줄은 **단 한순간도 살아 있지 않은** 위임이고, 맡긴
    // 사람은 승인함에서 「맡겨 뒀다」고 믿는다.
    // 🔵 통로가 **먼저** 거른다(400). 여기까지 오는 것은 통로를 거치지 않은 길이
    // 생겼을 때뿐이고, 그때 막는 것이 이 제약의 일이다.
    check("portal_approval_delegations_valid_range", sql`ends_at > starts_at`),
    // 「A 가 A 를 대신한다」는 뜻이 없는 줄이다. 본인은 판정 함수가 언제나 목록 맨
    // 앞에 넣어 주므로 이런 줄은 아무것도 늘리지 않는다.
    // 🔴 포털 번호 둘이 **다른데** A/S 계정 하나로 모일 수는 없다 —
    // `users_sso_subject_unique` 가 한 번호에 한 계정만 허락한다. 그래서 이 제약에
    // 걸리는 줄은 포털이 같은 사람을 둘로 보낸 경우뿐이고, 통로가 먼저 400 으로
    // 거른다(제약은 그 통로를 안 거친 길을 위한 마지막 벽이다).
    check(
      "portal_approval_delegations_different_users",
      sql`delegate_user_id <> delegator_user_id`
    ),
  ]
);
